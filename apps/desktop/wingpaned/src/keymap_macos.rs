/// USB HID keyboard page 0x07 to macOS virtual key codes.
pub fn mac_keycode(usage: u16) -> Option<u16> {
    Some(match usage {
        0x04..=0x1d => [
            0x00, 0x0b, 0x08, 0x02, 0x0e, 0x03, 0x05, 0x04, 0x22, 0x26, 0x28, 0x25, 0x2e, 0x2d,
            0x1f, 0x23, 0x0c, 0x0f, 0x01, 0x11, 0x20, 0x09, 0x0d, 0x07, 0x10, 0x06,
        ][(usage - 4) as usize],
        0x1e..=0x26 => {
            [0x12, 0x13, 0x14, 0x15, 0x17, 0x16, 0x1a, 0x1c, 0x19][(usage - 0x1e) as usize]
        }
        0x27 => 0x1d,
        0x28 => 0x24,
        0x29 => 0x35,
        0x2a => 0x33,
        0x2b => 0x30,
        0x2c => 0x31,
        0x2d => 0x1b,
        0x2e => 0x18,
        0x2f => 0x21,
        0x30 => 0x1e,
        0x31 => 0x2a,
        0x33 => 0x29,
        0x34 => 0x27,
        0x35 => 0x32,
        0x36 => 0x2b,
        0x37 => 0x2f,
        0x38 => 0x2c,
        0x3a..=0x45 => [
            0x7a, 0x78, 0x63, 0x76, 0x60, 0x61, 0x62, 0x64, 0x65, 0x6d, 0x67, 0x6f,
        ][(usage - 0x3a) as usize],
        0x49 => 0x72,
        0x4a => 0x73,
        0x4b => 0x74,
        0x4c => 0x75,
        0x4d => 0x77,
        0x4e => 0x79,
        0x4f => 0x7c,
        0x50 => 0x7b,
        0x51 => 0x7d,
        0x52 => 0x7e,
        0x53 => 0x47,
        0x54 => 0x4b,
        0x55 => 0x43,
        0x56 => 0x4e,
        0x57 => 0x45,
        0x58 => 0x4c,
        0x59 => 0x53,
        0x5a => 0x54,
        0x5b => 0x55,
        0x5c => 0x56,
        0x5d => 0x57,
        0x5e => 0x58,
        0x5f => 0x59,
        0x60 => 0x5b,
        0x61 => 0x5c,
        0x62 => 0x52,
        0x63 => 0x41,
        0x67 => 0x51,
        0xe0 => 0x3b,
        0xe1 => 0x38,
        0xe2 => 0x3a,
        0xe3 => 0x37,
        0xe4 => 0x3e,
        0xe5 => 0x3c,
        0xe6 => 0x3d,
        0xe7 => 0x36,
        _ => return None,
    })
}

/// Inverse of the supported HID keyboard-page mapping.
pub fn hid_usage(mac: u16) -> Option<u16> {
    (0..=0xe7).find(|&usage| mac_keycode(usage) == Some(mac))
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn hid_usage_roundtrips_every_mapped_usage() {
        for usage in 0..=u16::MAX {
            if let Some(mac) = mac_keycode(usage) { assert_eq!(hid_usage(mac), Some(usage)); }
        }
        assert_eq!(hid_usage(u16::MAX), None);
    }
    #[test]
    fn maps_common_keys_and_keypad_uniquely() {
        assert_eq!(mac_keycode(4), Some(0));
        assert_eq!(mac_keycode(0x28), Some(0x24));
        assert_eq!(mac_keycode(0x59), Some(0x53));
        let a = mac_keycode(4).unwrap();
        let b = mac_keycode(0x59).unwrap();
        assert_ne!(a, b);
    }
}
